export class ForgotPasswordPage {
  readonly email = signal<string>('maia@bgdcash.com.br');
  readonly sent = signal<boolean>(false);

  onSendRecovery(): void {
    if (this.email().trim()) {
      this.sent.set(true);
    }
  }
}
